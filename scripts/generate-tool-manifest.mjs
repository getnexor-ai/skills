#!/usr/bin/env node
// generate-tool-manifest — regenerate docs/mcp-tool-manifest.json from the
// public MCP server's source.
//
//   node scripts/generate-tool-manifest.mjs <path-to-nexor-mcp-public-checkout>
//   node scripts/generate-tool-manifest.mjs ../nexor-mcp-public --ref origin/main   # union with a git ref
//   node scripts/generate-tool-manifest.mjs ../nexor-mcp-public --check             # exit 1 if stale
//
// Tool names are read from `name: '<snake_case>'` entries in
// src/application/tools/*.tools.ts — from the working tree, plus every
// `--ref` (repeatable) read through `git show`, so a feature checkout that lags
// main still produces a complete manifest. Names listed under `pending` in the
// existing manifest (announced by in-flight MCP PRs) are kept until the source
// actually declares them, then promoted to `tools` automatically.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MANIFEST_PATH = path.join(ROOT, "docs", "mcp-tool-manifest.json");
const TOOLS_SUBDIR = path.join("src", "application", "tools");
// `name: 'x',` at the start of a line or right after `{` / `,` — the shape of a
// ToolDefinition literal, whether it is one-per-line or inlined.
const NAME_RE = /(?:^|[{,])\s*name:\s*['"]([a-z][a-z0-9_]*)['"]\s*,/gm;

/** Tool names declared in a *.tools.ts source string. */
export function extractToolNames(source) {
  const names = new Set();
  for (const m of source.matchAll(NAME_RE)) names.add(m[1]);
  return names;
}

/** Tool names declared in an MCP checkout's working tree. */
export function readToolNames(mcpRepo) {
  const dir = path.join(mcpRepo, TOOLS_SUBDIR);
  if (!existsSync(dir)) throw new Error(`No ${TOOLS_SUBDIR} under ${mcpRepo} — is that the public MCP checkout?`);
  const names = new Set();
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".tools.ts")) continue;
    for (const n of extractToolNames(readFileSync(path.join(dir, f), "utf8"))) names.add(n);
  }
  return [...names].sort();
}

/** Tool names declared at a git ref of the MCP checkout (e.g. origin/main). */
export function readToolNamesAtRef(mcpRepo, ref) {
  const git = (args) => execFileSync("git", ["-C", mcpRepo, ...args], { encoding: "utf8" });
  const files = git(["ls-tree", "--name-only", ref, `${TOOLS_SUBDIR}/`])
    .split("\n")
    .filter((f) => f.endsWith(".tools.ts"));
  const names = new Set();
  for (const f of files) for (const n of extractToolNames(git(["show", `${ref}:${f}`]))) names.add(n);
  return [...names].sort();
}

/** Merge freshly read names with the previous manifest's pending list. */
export function buildManifest(tools, previous = {}) {
  const found = new Set(tools);
  const pending = (previous.pending ?? []).filter((n) => !found.has(n)).sort();
  return {
    $comment:
      "Generated by scripts/generate-tool-manifest.mjs from the public MCP source. `tools` are declared in src/application/tools/*.tools.ts; `pending` are announced names not yet in the source (kept until they land). Skills may only reference names from either list.",
    source: previous.source ?? "getnexor-ai/nexor-mcp-public src/application/tools/*.tools.ts",
    generated_at: new Date().toISOString().slice(0, 10),
    tools,
    pending,
  };
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const refs = args.flatMap((a, i) => (a === "--ref" && args[i + 1] ? [args[i + 1]] : []));
  const repo = args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--ref");
  if (!repo) {
    console.error("usage: node scripts/generate-tool-manifest.mjs <path-to-mcp-repo> [--ref <git-ref>]... [--check]");
    process.exit(2);
  }
  const previous = existsSync(MANIFEST_PATH) ? JSON.parse(readFileSync(MANIFEST_PATH, "utf8")) : {};
  const names = new Set(readToolNames(path.resolve(repo)));
  for (const ref of refs) for (const n of readToolNamesAtRef(path.resolve(repo), ref)) names.add(n);
  const next = buildManifest([...names].sort(), previous);

  const added = next.tools.filter((n) => !(previous.tools ?? []).includes(n));
  const removed = (previous.tools ?? []).filter((n) => !next.tools.includes(n));
  const promoted = (previous.pending ?? []).filter((n) => next.tools.includes(n));

  if (check) {
    if (added.length || removed.length) {
      console.error(`manifest is stale — added: ${added.join(", ") || "none"}; removed: ${removed.join(", ") || "none"}`);
      process.exit(1);
    }
    console.log(`manifest is current (${next.tools.length} tools, ${next.pending.length} pending)`);
    return;
  }

  writeFileSync(MANIFEST_PATH, JSON.stringify(next, null, 2) + "\n");
  console.log(`wrote ${path.relative(ROOT, MANIFEST_PATH)}: ${next.tools.length} tools, ${next.pending.length} pending`);
  if (added.length) console.log(`  added   : ${added.join(", ")}`);
  if (removed.length) console.log(`  removed : ${removed.join(", ")}`);
  if (promoted.length) console.log(`  promoted: ${promoted.join(", ")}`);
  if (next.pending.length) console.log(`  pending : ${next.pending.join(", ")}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
